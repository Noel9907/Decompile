"""Render a fitted scene program as runnable Python source ("decompiled source").

The source constructs the SAME program object through the engine's public constructors
(decompile.projective_program.ProjectiveProgram / decompile.scene_program.SceneProgram) and runs the engine's
simulator. ``exact`` uses full-precision literals (tests execute it and compare against program_from_json);
``display`` rounds literals for reading. Nothing here estimates or simulates anything.
"""

from __future__ import annotations

import math
from fractions import Fraction

from decompile import projective_program as pprog


def _f(v: float, exact: bool, nd: int = 4) -> str:
    if exact:
        return repr(float(v))
    a = abs(v)
    if a != 0 and (a < 1e-3 or a >= 1e5):
        return f"{v:.3e}"
    return f"{v:.{nd}f}"


def _vec(vs, exact: bool, nd: int = 4) -> str:
    return "(" + ", ".join(_f(v, exact, nd) for v in vs) + ")"


def _line(code: str, comment: str = "", width: int = 48) -> str:
    return f"{code:<{width}}# {comment}" if comment else code


def program_source(data: dict, *, context: dict | None = None, exact: bool = False) -> str:
    ctx = context or {}
    head = [f"# {ctx['title']}" if ctx.get("title") else "# Decompiled scene program",
            "# Generated by Decompile from measured video evidence. Runs against the Decompile engine.", ""]
    if data.get("kind") == pprog.PROGRAM_KIND:
        t0 = Fraction(data["t0"]["num"], data["t0"]["den"])
        g = data["g"]
        gm = math.sqrt(sum(v * v for v in g))
        prov = data.get("provenance", {})
        cf = prov.get("counterfactual")
        gap = prov.get("contact_gap_frames")
        hfov = prov.get("hfov_used_deg")
        lines = head + [
            "from fractions import Fraction",
            "from decompile import projective_program as pp",
            "",
            "program = pp.ProjectiveProgram(",
            _line(f"    object_id={data['object_id']!r},", "the tracked body"),
            _line(f"    t0=Fraction({t0.numerator}, {t0.denominator}),", f"s, first measured frame ({float(t0):.3f} s)"),
            _line(f"    principal_point={_vec(data['principal_point'], exact, 1)},", "px, image centre"),
            _line(f"    f_px={_f(data['f_px'], exact, 2)},",
                  f"px, {hfov:g} deg FOV prior" if hfov else "px, focal length"),
            _line(f"    p0={_vec(data['p0'], exact)},", "start position (ball diameters)"),
            _line(f"    v0={_vec(data['v0'], exact)},",
                  f"COUNTERFACTUAL: thrown x{cf['velocity_scale']:g}" if cf and cf.get("velocity_scale") else "start velocity (D/s)"),
            _line(f"    g={_vec(g, exact, 3)},",
                  f"gravity, |g| = {gm:.1f} D/s^2" + (" (counterfactual)" if cf and cf.get("gravity_scale") else "")),
            _line(f"    normal={_vec(data['normal'], exact)},", "floor normal"),
            _line(f"    plane_offset={_f(data['plane_offset'], exact)},",
                  "COUNTERFACTUAL: floor removed" if cf and cf.get("floor_removed") else "floor through the bounce"),
            _line(f"    restitution={_f(data['restitution'], exact)},",
                  "COUNTERFACTUAL" if cf and cf.get("restitution") is not None
                  else (f"measured: bounce in frames {gap[0]}-{gap[1]}" if gap else "measured at the bounce")),
            _line(f"    k_tangential={_vec(data['k_tangential'], exact)},", "bounce spin-off / friction"),
            "    provenance={'source': 'decompile_web'},",
            ")",
            "",
            _line("times = [program.t0 + Fraction(k, 100) for k in range(100)]", "1 s at 100 Hz"),
            _line("sim = pp.simulate(program, times)", "-> x_px, y_px, diameter_px, contacts"),
        ]
        return "\n".join(lines) + "\n"
    b, a, planes = data["body"], data["acceleration"], data["planes"]
    t0 = Fraction(b["t0"]["num"], b["t0"]["den"])
    cf = data.get("provenance", {}).get("counterfactual")
    lines = head + [
        "from fractions import Fraction",
        "from decompile import scene_program as sp",
        "",
        "program = sp.SceneProgram(",
        "    body=sp.Body(",
        _line(f"        object_id={b['object_id']!r},", "the tracked body"),
        _line(f"        t0=Fraction({t0.numerator}, {t0.denominator}),", f"s, first measured frame"),
        _line(f"        x0={_f(b['x0'], exact, 2)}, y0={_f(b['y0'], exact, 2)},", "px - initial centre"),
        _line(f"        vx0={_f(b['vx0'], exact, 2)}, vy0={_f(b['vy0'], exact, 2)},",
              f"COUNTERFACTUAL: thrown x{cf['velocity_scale']:g}" if cf and cf.get("velocity_scale") else "px/s - initial velocity"),
        "    ),",
        _line(f"    acceleration=sp.UniformAcceleration(ax={_f(a['ax'], exact, 2)}, ay={_f(a['ay'], exact, 2)}),",
              "px/s^2 (+y down)" + (" (counterfactual)" if cf and cf.get("gravity_scale") else "")),
        "    planes=(" + ("),  # COUNTERFACTUAL: floor removed" if not planes else ""),
    ]
    for p in planes:
        lines += [
            "        sp.AxisPlane(",
            _line(f"            axis={p['axis']!r}, position_px={_f(p['position_px'], exact, 2)}, keep_side={p['keep_side']!r},",
                  "inferred contact boundary"),
            _line(f"            restitution={_f(p['restitution'], exact)},",
                  "COUNTERFACTUAL" if cf and cf.get("restitution") is not None else "measured at the contact"),
            "        ),",
        ]
    lines += ([] if not planes else ["    ),"]) + [
        "    provenance={'source': 'decompile_web'},",
        ")",
        "",
        _line("times = [program.body.t0 + Fraction(k, 100) for k in range(100)]", "1 s at 100 Hz"),
        _line("sim = sp.simulate(program, times)", "-> x_px, y_px, velocities, contacts"),
    ]
    return "\n".join(lines) + "\n"


def sources(data: dict, context: dict | None = None) -> dict:
    return {"display": program_source(data, context=context), "exact": program_source(data, context=context, exact=True)}
